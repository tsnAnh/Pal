import Foundation

public protocol PasteboardStore: Sendable {
    var accessAllowed: Bool { get }
    func types() -> [String]
    func text() -> String?
    func image() -> ClipboardImage?
    func replace(text: String) -> Bool
    func replace(image: Data, type: String) -> Bool
}

public struct SystemClipboard: ClipboardProviding {
    static let withheldTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType"]
    static let textTypes: Set<String> = [
        "public.utf8-plain-text", "public.plain-text", "public.utf16-plain-text", "public.utf16-external-plain-text", "NSStringPboardType",
    ]
    static let imageTypes: Set<String> = ["public.png", "public.jpeg", "public.tiff"]
    static let fileTypes: Set<String> = ["public.file-url"]
    static let maximumWrittenText = 100_000

    private let store: any PasteboardStore

    public init(store: any PasteboardStore) {
        self.store = store
    }

    public func read(includeImage: Bool, textLimit: Int, imageLimit: Int) async throws -> ClipboardReadRecord {
        try checkAccess()
        let present = Set(store.types())
        let kinds = Self.kinds(of: present)
        if !present.isDisjoint(with: Self.withheldTypes) { return ClipboardReadRecord(types: kinds, concealed: true) }
        var record = ClipboardReadRecord(types: kinds)
        if kinds.contains("text"), let text = store.text() {
            let bytes = Array(text.utf8)
            record.text = TextCap.capture(bytes, totalBytes: bytes.count, limit: textLimit)
        }
        if includeImage, kinds.contains("image"), let image = store.image() {
            record.imageBytes = image.data.count
            if image.data.count <= imageLimit { record.image = image }
        }
        return record
    }

    public func write(text: String) async throws -> ClipboardWriteRecord {
        try checkAccess()
        guard text.count <= Self.maximumWrittenText else {
            throw DeviceProviderError.invalidArgs("text must be at most \(Self.maximumWrittenText) characters.")
        }
        guard store.replace(text: text) else { throw DeviceProviderError.failed("The clipboard could not be changed.") }
        return ClipboardWriteRecord(kind: "text", size: text.count)
    }

    public func write(imageBase64: String, imageLimit: Int) async throws -> ClipboardWriteRecord {
        try checkAccess()
        guard let data = Data(base64Encoded: imageBase64, options: .ignoreUnknownCharacters), !data.isEmpty else {
            throw DeviceProviderError.invalidArgs("image_base64 is not valid base64.")
        }
        guard data.count <= imageLimit else { throw DeviceProviderError.invalidArgs("The image must be at most \(imageLimit) bytes.") }
        guard let type = Self.imageType(of: data) else { throw DeviceProviderError.invalidArgs("The image must be a PNG or JPEG.") }
        guard store.replace(image: data, type: type) else { throw DeviceProviderError.failed("The clipboard could not be changed.") }
        return ClipboardWriteRecord(kind: "image", size: data.count)
    }

    private func checkAccess() throws {
        guard store.accessAllowed else { throw DeviceProviderError.permissionDenied }
    }

    static func kinds(of present: Set<String>) -> [String] {
        var kinds: [String] = []
        if !present.isDisjoint(with: textTypes) { kinds.append("text") }
        if !present.isDisjoint(with: imageTypes) { kinds.append("image") }
        if !present.isDisjoint(with: fileTypes) { kinds.append("file_urls") }
        if kinds.isEmpty, !present.subtracting(withheldTypes).isEmpty { kinds.append("other") }
        return kinds
    }

    static func imageType(of data: Data) -> String? {
        let head = [UInt8](data.prefix(4))
        if head == [0x89, 0x50, 0x4E, 0x47] { return "public.png" }
        if head.starts(with: [0xFF, 0xD8, 0xFF]) { return "public.jpeg" }
        return nil
    }
}

#if os(macOS)
import AppKit

public struct GeneralPasteboard: PasteboardStore {
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    public init() {}

    public var accessAllowed: Bool {
        if #available(macOS 15.4, *) { return NSPasteboard.general.accessBehavior != .alwaysDeny }
        return true
    }

    public func types() -> [String] {
        (NSPasteboard.general.types ?? []).map(\.rawValue)
    }

    public func text() -> String? {
        NSPasteboard.general.string(forType: .string)
    }

    public func image() -> ClipboardImage? {
        let board = NSPasteboard.general
        if let data = board.data(forType: .png) { return ClipboardImage(data: data, mime: "image/png") }
        if let data = board.data(forType: NSPasteboard.PasteboardType("public.jpeg")) { return ClipboardImage(data: data, mime: "image/jpeg") }
        guard let tiff = board.data(forType: .tiff), let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) else {
            return nil
        }
        return ClipboardImage(data: png, mime: "image/png")
    }

    public func replace(text: String) -> Bool {
        let board = NSPasteboard.general
        board.clearContents()
        board.declareTypes([.string, Self.autoGenerated], owner: nil)
        return board.setString(text, forType: .string) && board.setData(Data(), forType: Self.autoGenerated)
    }

    public func replace(image: Data, type: String) -> Bool {
        let board = NSPasteboard.general
        let imageType = NSPasteboard.PasteboardType(type)
        board.clearContents()
        board.declareTypes([imageType, Self.autoGenerated], owner: nil)
        return board.setData(image, forType: imageType) && board.setData(Data(), forType: Self.autoGenerated)
    }
}
