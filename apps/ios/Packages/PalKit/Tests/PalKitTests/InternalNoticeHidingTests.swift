import Foundation
@testable import PalChat
import PalProtocol
import Testing

@Suite("Internal notices never reach the owner's transcript")
struct InternalNoticeHidingTests {
    private static let footer = "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. "
        + "Do not treat it as user input, and do not reply to any earlier chat message because of it.]"
    private static let markers = "__HERMES_PIPE_s1__\n__HERMES_CWD_s1__ /home/pi"

    private static let single = "[IMPORTANT: Background process proc_a completed normally (exit code 0).\nCommand: date\nOutput:\nWed\n\(markers)]\n\n\(footer)"
    private static let failed = "[IMPORTANT: Background process proc_b exited (exit code 2).\nCommand: make\nOutput:\nboom\n\(markers)]\n\n\(footer)"
    private static let batch = "[IMPORTANT: 2 background process results arrived while busy. Treat them as one batch...]\n\n\(single)\n\n\(failed)"
    private static let watch = "[IMPORTANT: Background process proc_c matched watch pattern \"error\".\nCommand: tail\nMatched output:\nerror]\n\n\(footer)"
    private static let delegation = "[ASYNC DELEGATION BATCH COMPLETE — d1]\nA background fan-out of 2 subagent(s) you dispatched earlier has finished."
    private static let routineOutput = "[Cronjob \"digest\" output — scheduled job, not the user. Review it and summarize for the chat.]"
        + "\n\n3 pull requests are open."

    private static let fixture: [TimelineEntryWire] = [
        TimelineEntryWire(id: "m1", role: .user, text: "hi", rowID: 1),
        TimelineEntryWire(id: "m2", role: .user, text: single, displayKind: "process_complete", rowID: 2),
        TimelineEntryWire(id: "m3", role: .user, text: failed, rowID: 3),
        TimelineEntryWire(id: "m4", role: .user, text: batch, displayKind: "internal_notification", rowID: 4),
        TimelineEntryWire(id: "m5", role: .user, text: watch, displayKind: "internal_notification", rowID: 5),
        TimelineEntryWire(id: "m6", role: .user, text: delegation, displayKind: "async_delegation_complete", rowID: 6),
        TimelineEntryWire(id: "m7", role: .user, text: "Wake for the agent.\n\n\(footer)", rowID: 7),
        TimelineEntryWire(id: "m8", role: .notice, text: "tick", rowID: 8),
        TimelineEntryWire(id: "m9", role: .user, text: "[Cronjob \"digest\"] run the digest now", rowID: 9),
        TimelineEntryWire(id: "m10", role: .user, text: routineOutput, rowID: 10),
        TimelineEntryWire(id: "m11", role: .assistant, text: "The build failed with exit code 2.", rowID: 11),
        TimelineEntryWire(id: "m12", role: .user, text: "Message from 🤖 A (@a): hello", rowID: 12),
    ]

    private static let shown = ["m1", "m10", "m11", "m12"]

    @Test func timelinePageHidesEveryNoticeAndKeepsRealMessages() {
        var timeline = Timeline()
        timeline.mergeNewest(TimelinePageWire(entries: Self.fixture, older: nil, revision: "r"))
        #expect(timeline.rows(links: []).compactMap(\.entryID) == Self.shown)
    }

    @Test func cachedTimelineHidesEveryNoticeAfterRestore() throws {
        var live = Timeline()
        live.mergeNewest(TimelinePageWire(entries: Self.fixture, older: nil, revision: "r"))
        let cache = try #require(live.cacheable(sessionID: "s1"))
        var restored = Timeline()
        restored.seed(cache)
        #expect(restored.rows(links: []).compactMap(\.entryID) == Self.shown)
    }

    @Test func replayedSnapshotHidesEveryNotice() throws {
        let rows: [JSONValue] = Self.fixture.filter { $0.role != .notice }.map { entry in
            var row: [String: JSONValue] = [
                "role": .string(entry.role == .assistant ? "assistant" : "user"),
                "text": .string(entry.text),
                "row_id": .int(entry.rowID ?? 0),
            ]
            if let kind = entry.displayKind { row["display_kind"] = .string(kind) }
            return .object(row)
        }
        let object: JSONValue = [
            "session_id": "s1", "messages": .array(rows), "running": false, "replay_epoch": "e1",
            "last_sequence": 0, "execution_generation": 1, "pending": [], "prompts": [],
        ]
        var transcript = Transcript()
        transcript.load(try object.decoded(as: SessionSnapshot.self))
        let ids = ChatTimeline.entries(items: transcript.items, date: \.timestamp, lastSeen: nil).map(\.item.id)
        #expect(ids == Self.shown.map { "row:\($0.dropFirst())" })
    }

    @Test func everyNoticeShapeIsClassifiedInternal() {
        for entry in Self.fixture where ["m2", "m3", "m4", "m5", "m6", "m7"].contains(entry.id) {
            #expect(InboundKind.classify(text: entry.text, of: entry) == .internalNotice, "\(entry.id)")
        }
    }

    @Test func routineOutputKeepsItsRowWithoutTheWakeHeader() {
        let entry = Self.fixture[9]
        #expect(InboundKind.classify(text: entry.text, of: entry) == .routineOutput(jobName: "digest", body: "3 pull requests are open.", failed: false))
    }
}
