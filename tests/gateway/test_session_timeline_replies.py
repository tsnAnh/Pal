def test_a_page_cursor_walks_a_joined_transcript_once(db, tmp_path):
    from gateway.session_timeline import load_timeline, page
    for n in range(4):
        _ask(db, f'Q{n}')
        _say(db, f'A{n}')
        _notice(db)
        _say(db, f'B{n}')
    built = load_timeline(str(tmp_path), db, 's1', str(tmp_path))
    cursor, seen = None, []
    while True:
        result = page(built, cursor, 2)
        seen = result['entries'] + seen
        cursor = result['older']
        if cursor is None:
            break
    assert seen == list(built.entries)
    assert _replies(seen) == [f'A{n}\n\nB{n}' for n in range(4)]
