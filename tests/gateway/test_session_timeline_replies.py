import json

import pytest

_FOOTER = ('[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. '
           'Do not treat it as user input.]')
_PROCESS = (f'[IMPORTANT: Background process proc_a completed normally (exit code 0).\n'
            f'Command: make\nOutput:\nok]\n\n{_FOOTER}')
_WATCH = (f'[IMPORTANT: Background process proc_c matched watch pattern "error".\n'
          f'Command: tail\nMatched output:\nerror]\n\n{_FOOTER}')
_DELEGATION = '[ASYNC DELEGATION BATCH COMPLETE — d1]\nTwo subagents finished.'
_BOT_DM = 'Message from 🤖 Atlas (@atlas): status please'
_ROUTINE = '[Cronjob "digest"] run the digest now'


@pytest.fixture
def db(tmp_path):
    from hermes_state import SessionDB
    store = SessionDB(tmp_path / 'state.db')
    store.create_session('s1', source='tui')
    yield store
    store.close()


def _load(db, tmp_path, target='s1'):
    from gateway.session_timeline import load_timeline
    return list(load_timeline(str(tmp_path), db, target, str(tmp_path)).entries)


def _replies(entries):
    return [entry['text'] for entry in entries if entry['role'] == 'assistant']


def _ask(db, text='check the build', **fields):
    db.append_message('s1', 'user', text, **fields)


def _say(db, text, **fields):
    return db.append_message('s1', 'assistant', text, **fields)


def _notice(db, text=_PROCESS, kind='process_complete'):
    db.append_message('s1', 'user', text, display_kind=kind, display_metadata={'display_text': 'Finished'})


def _tool(db, name, result, call_id='c1', text=''):
    _say(db, text, tool_calls=[{'id': call_id, 'type': 'function', 'function': {'name': name, 'arguments': '{}'}}])
    db.append_message('s1', 'tool', result, tool_call_id=call_id, tool_name=name)


def test_a_notice_reply_joins_the_owner_reply_without_touching_stored_rows(db, tmp_path):
    _ask(db)
    _say(db, 'Build started.', reasoning='plan')
    _notice(db)
    last = _say(db, 'Build passed.', reasoning='read output')
    stored = db.get_messages_as_conversation('s1', include_row_ids=True)
    entries = _load(db, tmp_path)
    assert [(entry['role'], entry['text']) for entry in entries] == [
        ('user', 'check the build'), ('assistant', 'Build started.\n\nBuild passed.'), ('user', _PROCESS)]
    joined = entries[1]
    assert joined['id'] == stored[1]['message_uid'] and joined['row_id'] == last
    assert joined['timestamp'] == stored[1]['timestamp']
    assert 'plan' in joined['reasoning'] and 'read output' in joined['reasoning']
    assert db.get_messages_as_conversation('s1', include_row_ids=True) == stored


def test_a_joined_reply_keeps_the_tools_of_both_sides(db, tmp_path):
    _ask(db)
    _tool(db, 'terminal', '{"output": "ok", "exit_code": 0}', 'c1', 'Starting.')
    _say(db, 'Started.')
    _notice(db)
    _tool(db, 'terminal', '{"output": "ok", "exit_code": 0, "error": null}', 'c2', 'Reading the log.')
    _say(db, 'All green.')
    _ask(db, 'thanks')
    [reply] = [entry for entry in _load(db, tmp_path) if entry['role'] == 'assistant']
    assert reply['text'] == 'Starting.\n\nStarted.\n\nReading the log.\n\nAll green.'
    assert [tool['call_id'] for tool in reply['tools']] == ['c1', 'c2']


