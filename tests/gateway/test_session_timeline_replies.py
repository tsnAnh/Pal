@pytest.mark.parametrize('name, result', [
    ('clarify', json.dumps({'question': 'Which?', 'answer': 'a'})),
    ('manage_connections', json.dumps({'op_id': 'o', 'status': 'settled', 'targets': []})),
    ('terminal', json.dumps({'output': '', 'exit_code': -1, 'error': 'denied', 'status': 'blocked'})),
    ('terminal', json.dumps({'status': 'approval_required', 'command': 'rm -rf build'})),
    ('execute_code', json.dumps({'status': 'error', 'error': 'BLOCKED: no user is present to approve it.'})),
    ('send_message', json.dumps({'error': 'BLOCKED: This message was NOT sent.'})),
    ('mcp_mail_send', json.dumps({'error': 'The owner did not approve it.', 'code': 'action_denied'})),
    ('mcp_mail_send', json.dumps({'error': 'It needs approval.', 'code': 'approval_unavailable'})),
    ('slack_send_message', json.dumps({'error': 'Nothing was sent.', 'code': 'approval_required'})),
    ('terminal', json.dumps({'error': 'The owner did not approve it.', 'code': 'owner_denied'})),
])
@pytest.mark.parametrize('gated_side', ['notice', 'owner'])
def test_a_turn_that_needed_the_owner_stays_its_own_entry(db, tmp_path, name, result, gated_side):
    _ask(db)
    if gated_side == 'owner':
        _tool(db, name, result)
    _say(db, 'Build started.')
    _notice(db)
    if gated_side == 'notice':
        _tool(db, name, result)
    _say(db, 'Build passed.')
    replies = [text for text in _replies(_load(db, tmp_path)) if text]
    assert replies == ['Build started.', 'Build passed.']


